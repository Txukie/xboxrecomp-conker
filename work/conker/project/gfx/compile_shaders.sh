#!/bin/sh
# Regenerate gfx_vulkan_shaders.h from shaders/*.{vert,frag} (next to this script).
# Needs glslc (shaderc). The generated header is committed so normal builds
# do not need a shader compiler.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
dir="$here/shaders"
out="$here/gfx_vulkan_shaders.h"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

{
    echo "/* Generated by gfx/compile_shaders.sh from gfx/shaders. Do not edit. */"
    echo "#ifndef GFX_VULKAN_SHADERS_H"
    echo "#define GFX_VULKAN_SHADERS_H"
    echo "#include <stdint.h>"
    for src in "$dir"/screen.vert "$dir"/screen.frag; do
        name=$(basename "$src" | tr . _)
        glslc -O --target-env=vulkan1.0 -o "$tmp/$name.spv" "$src"
        echo "static const uint32_t gfx_spv_${name}[] = {"
        od -An -v -t x4 "$tmp/$name.spv" | sed -e 's/  */ /g' -e 's/^ //' -e 's/ /, 0x/g' -e 's/^/    0x/' -e 's/$/,/'
        echo "};"
    done
    echo "#endif"
} > "$out"
echo "wrote $out"
